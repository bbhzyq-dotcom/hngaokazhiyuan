def get_all_majors():
    majors = []
    major_id = 1
    for discipline_code in sorted(DISCIPLINES_DB.keys()):
        discipline = DISCIPLINES_DB[discipline_code]
        categories = discipline.get("categories", {})
        for category_code in sorted(categories.keys()):
            category = categories[category_code]
            category_name = category["name"]
            majors_list = category["majors"]
            for m in majors_list:
                majors.append({
                    "id": f"{major_id:05d}",
                    "code": m["code"],
                    "name": m["name"],
                    "category": category_name,
                    "discipline": discipline["name"],
                    "discipline_code": discipline_code,
                    "category_code": category_code,
                    "duration": m["duration"],
                    "degree": get_degree(discipline["name"], m["duration"]),
                })
                major_id += 1
    return majors

